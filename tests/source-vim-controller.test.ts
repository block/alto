import { describe, expect, it } from 'vitest'
import { SourceVimController, type VimResult } from '../program/plugins/source-vim-controller.js'

function keys(vim: SourceVimController, sequence: string[]): VimResult {
  let result: VimResult = { handled: false }
  for (const key of sequence) result = vim.key(key)
  return result
}

describe('source viewer Vim controller', () => {
  it('preserves the preferred column across short lines and lets Escape cancel counts', () => {
    const vim = new SourceVimController('123456\nx\n123456', { line: 1, column: 4 })
    vim.key('j')
    expect(vim.state.cursor).toEqual({ line: 2, column: 0 })
    vim.key('j')
    expect(vim.state.cursor).toEqual({ line: 3, column: 4 })
    keys(vim, ['2', 'Escape', 'k'])
    expect(vim.state.cursor.line).toBe(2)
    keys(vim, ['$', 'j'])
    expect(vim.state.cursor.column).toBe(5)
  })

  it('supports counted file, first nonblank, last nonblank and paragraph motions', () => {
    const vim = new SourceVimController('  first  \nsecond\n\n  fourth\nfifth\n\nlast')
    keys(vim, ['3', 'G'])
    expect(vim.state.cursor).toEqual({ line: 3, column: 0 })
    keys(vim, ['4', 'g', 'g'])
    expect(vim.state.cursor).toEqual({ line: 4, column: 2 })
    keys(vim, ['g', 'g', 'g', '_'])
    expect(vim.state.cursor).toEqual({ line: 1, column: 6 })
    vim.key('}')
    expect(vim.state.cursor.line).toBe(3)
    vim.key('}')
    expect(vim.state.cursor.line).toBe(6)
    vim.key('{')
    expect(vim.state.cursor.line).toBe(3)
    keys(vim, ['g', 'g', '2', '$'])
    expect(vim.state.cursor).toEqual({ line: 2, column: 5 })
    vim.key('Enter')
    expect(vim.state.cursor.line).toBe(3)
  })

  it('uses words, WORDs and backward word ends', () => {
    const vim = new SourceVimController('one.two three four')
    vim.key('W')
    expect(vim.state.cursor.column).toBe(8)
    keys(vim, ['g', 'e'])
    expect(vim.state.cursor.column).toBe(6)
    keys(vim, ['g', 'E'])
    expect(vim.state.cursor.column).toBe(0)
    keys(vim, ['2', 'w'])
    expect(vim.state.cursor.column).toBe(4)
  })

  it('finds and tills counted characters and repeats in either direction', () => {
    const vim = new SourceVimController('a,b,c,d')
    keys(vim, ['2', 'f', ','])
    expect(vim.state.cursor.column).toBe(3)
    vim.key(';')
    expect(vim.state.cursor.column).toBe(5)
    vim.key(',')
    expect(vim.state.cursor.column).toBe(3)
    keys(vim, ['0', 't', ','])
    expect(vim.state.cursor.column).toBe(0)
    vim.key(';')
    expect(vim.state.cursor.column).toBe(2)
    vim.key(';')
    expect(vim.state.cursor.column).toBe(4)
    vim.key(',')
    expect(vim.state.cursor.column).toBe(2)
    keys(vim, ['F', ','])
    expect(vim.state.cursor.column).toBe(1)
    expect(keys(vim, ['f', 'z'])).toEqual({ handled: true })
    expect(vim.state.cursor.column).toBe(1)
    expect(vim.state.message).toContain('not found')
  })

  it('matches nested brackets and supports percentage navigation', () => {
    const vim = new SourceVimController('call(a, (b + c))\nnext\nthird\nlast')
    vim.key('%')
    expect(vim.state.cursor).toEqual({ line: 1, column: 15 })
    vim.key('%')
    expect(vim.state.cursor.column).toBe(4)
    keys(vim, ['5', '0', '%'])
    expect(vim.state.cursor.line).toBe(2)
    keys(vim, ['1', '0', '1', '%'])
    expect(vim.state.message).toContain('Percentage')
  })

  it('searches the current line before wrapping and preserves backward repeat direction', () => {
    const vim = new SourceVimController('cat Cat cat\ncat')
    vim.search('cat', 1)
    expect(vim.state.cursor).toEqual({ line: 1, column: 4 })
    vim.key('n')
    expect(vim.state.cursor.column).toBe(8)
    vim.search('cat', -1)
    expect(vim.state.cursor.column).toBe(4)
    vim.key('n')
    expect(vim.state.cursor.column).toBe(0)
    vim.key('n')
    expect(vim.state.cursor).toEqual({ line: 2, column: 0 })
    vim.key('N')
    expect(vim.state.cursor).toEqual({ line: 1, column: 0 })
    vim.search('Cat', 1)
    expect(vim.state.cursor.column).toBe(4)
    vim.key('n')
    expect(vim.state.cursor.column).toBe(4)
  })

  it('treats search text literally and preserves offsets after Unicode case mappings', () => {
    const vim = new SourceVimController('İ [a] [A]')
    vim.search('[a]', 1)
    expect(vim.state.cursor.column).toBe(2)
    vim.key('n')
    expect(vim.state.cursor.column).toBe(6)
    vim.search('missing', 1)
    expect(vim.state.message).toContain('Pattern not found')
  })

  it('searches whole words under the cursor with * and # and counted matches', () => {
    const vim = new SourceVimController('one someone one one')
    vim.key('*')
    expect(vim.state.cursor.column).toBe(12)
    keys(vim, ['2', 'n'])
    expect(vim.state.cursor.column).toBe(0)
    vim.key('#')
    expect(vim.state.cursor.column).toBe(16)
    vim.key('n')
    expect(vim.state.cursor.column).toBe(12)
  })

  it('multiplies operator counts and yanks exclusive versus inclusive motions', () => {
    const vim = new SourceVimController('one two three four five six seven')
    expect(keys(vim, ['2', 'y', '3', 'w']).yank).toBe('one two three four five six ')
    expect(vim.state.cursor.column).toBe(0)
    expect(keys(vim, ['y', 'e']).yank).toBe('one')
    expect(keys(vim, ['y', 'l']).yank).toBe('o')
    keys(vim, ['2', 'w'])
    expect(keys(vim, ['y', 'b']).yank).toBe('two ')
    expect(vim.state.cursor.column).toBe(4)
    expect(keys(vim, ['y', '$']).yank).toBe('two three four five six seven')
  })

  it('yanks counted lines and vertical motions with a final newline', () => {
    const vim = new SourceVimController('one\ntwo\nthree\nfour')
    expect(keys(vim, ['2', 'y', 'y']).yank).toBe('one\ntwo\n')
    expect(keys(vim, ['y', 'j']).yank).toBe('one\ntwo\n')
    vim.key('G')
    expect(vim.key('Y').yank).toBe('four\n')
    expect(keys(vim, ['y', 'g', 'g']).yank).toBe('one\ntwo\nthree\nfour\n')
  })

  it('yanks character searches and accepts search as an operator motion', () => {
    const vim = new SourceVimController('one, two, three')
    expect(keys(vim, ['y', 'f', ',']).yank).toBe('one,')
    expect(keys(vim, ['y', 't', ',']).yank).toBe('one')
    expect(keys(vim, ['y', '/']).command).toBe('forward')
    expect(vim.search('two', 1).yank).toBe('one, ')
  })

  it('normalizes backwards character selections and swaps their active endpoint', () => {
    const vim = new SourceVimController('abcdef', { line: 1, column: 4 })
    keys(vim, ['v', '2', 'h'])
    expect(vim.selection()).toEqual({ start: { line: 1, column: 2 }, end: { line: 1, column: 4 }, linewise: false })
    vim.key('o')
    expect(vim.state.cursor.column).toBe(4)
    expect(vim.key('y').yank).toBe('cde')
    expect(vim.state.mode).toBe('normal')
    expect(vim.state.cursor.column).toBe(2)
  })

  it('yanks visual lines and toggles between selection modes', () => {
    const vim = new SourceVimController('one\ntwo\nthree', { line: 3, column: 2 })
    keys(vim, ['V', 'k'])
    expect(vim.selection()).toEqual({ start: { line: 2, column: 0 }, end: { line: 3, column: 4 }, linewise: true })
    vim.key('v')
    expect(vim.state.mode).toBe('visual')
    vim.key('V')
    expect(vim.key('y').yank).toBe('two\nthree\n')
  })

  it('selects and yanks inner/around words and WORDs', () => {
    const vim = new SourceVimController('one.two three', { line: 1, column: 5 })
    expect(keys(vim, ['y', 'i', 'w']).yank).toBe('two')
    expect(keys(vim, ['y', 'a', 'w']).yank).toBe('two ')
    expect(keys(vim, ['y', 'i', 'W']).yank).toBe('one.two')
    keys(vim, ['v', 'i', 'w'])
    expect(vim.key('y').yank).toBe('one')
    expect(keys(vim, ['y', '2', 'i', 'w']).yank).toBe('one.')
  })

  it('handles nested delimiter objects, quote escapes, and empty inner objects', () => {
    const vim = new SourceVimController('f(outer(inner), "a\\\"b")', { line: 1, column: 10 })
    expect(keys(vim, ['y', 'i', '(']).yank).toBe('inner')
    expect(keys(vim, ['y', '2', 'a', '(']).yank).toBe('(outer(inner), "a\\\"b")')
    vim.setCursor({ line: 1, column: 18 })
    expect(keys(vim, ['y', 'i', '"']).yank).toBe('a\\\"b')
    vim.reset('()')
    expect(keys(vim, ['y', 'i', '(']).yank).toBe('')
    expect(keys(vim, ['v', 'i', '(']).handled).toBe(true)
    expect(vim.state.message).toContain('empty')
  })

  it('uses viewport-aware motions and scroll commands without stealing modified word keys', () => {
    const vim = new SourceVimController(Array.from({ length: 100 }, (_, index) => `line ${index}`).join('\n'))
    const context = { viewportLines: 20, firstVisibleLine: 30, lastVisibleLine: 49 }
    expect(vim.key('Ctrl+d', context)).toMatchObject({ scroll: 'page-down', scrollLines: 10 })
    expect(vim.state.cursor.line).toBe(11)
    expect(vim.key('Ctrl+u', context)).toMatchObject({ scroll: 'page-up', scrollLines: 10 })
    expect(vim.state.cursor.line).toBe(1)
    vim.key('Ctrl+f', context)
    expect(vim.state.cursor.line).toBe(19)
    vim.key('Ctrl+b', context)
    expect(vim.state.cursor.line).toBe(1)
    vim.key('H', context)
    expect(vim.state.cursor.line).toBe(30)
    vim.key('M', context)
    expect(vim.state.cursor.line).toBe(39)
    vim.key('L', context)
    expect(vim.state.cursor.line).toBe(49)
    expect(keys(vim, ['z', 'z']).scroll).toBe('center')
    expect(keys(vim, ['z', 't']).scroll).toBe('top')
    expect(keys(vim, ['z', 'b']).scroll).toBe('bottom')
    expect(vim.key('Ctrl+e').scroll).toBe('line-down')
    expect(vim.key('Ctrl+y').scroll).toBe('line-up')
  })

  it('keeps named marks and traverses jump history in both directions', () => {
    const vim = new SourceVimController('  one\n  two\n  three', { line: 1, column: 4 })
    keys(vim, ['m', 'a', 'G'])
    expect(vim.state.cursor.line).toBe(3)
    keys(vim, ['`', 'a'])
    expect(vim.state.cursor).toEqual({ line: 1, column: 4 })
    vim.key('Ctrl+o')
    expect(vim.state.cursor.line).toBe(3)
    vim.key('Ctrl+i')
    expect(vim.state.cursor).toEqual({ line: 1, column: 4 })
    keys(vim, ["'", 'a'])
    expect(vim.state.cursor).toEqual({ line: 1, column: 2 })
    vim.reset('new')
    keys(vim, ['`', 'a'])
    expect(vim.state.message).toContain('Mark not set')
  })

  it('supports line Ex commands and help while refusing edits', () => {
    const vim = new SourceVimController('first\n  second\nlast')
    vim.ex(':2')
    expect(vim.state.cursor).toEqual({ line: 2, column: 2 })
    vim.ex('$')
    expect(vim.state.cursor.line).toBe(3)
    expect(vim.ex('help').help).toBe(true)
    expect(vim.ex('nohlsearch')).toEqual({ handled: true })
    vim.ex('w')
    expect(vim.state.message).toContain('read-only')
    vim.key('i')
    expect(vim.state.mode).toBe('normal')
    expect(vim.state.message).toContain('read-only')
  })

  it('retains comment selection and clears pending commands on focus loss', () => {
    const vim = new SourceVimController('first\nsecond\nlast')
    vim.select({ line: 3, column: 0 }, { line: 2, column: 0 }, true)
    expect(vim.key('c').comment).toBe(true)
    expect(vim.selection()?.start.line).toBe(2)
    vim.key('2')
    vim.clearPending()
    expect(vim.state.pending).toBe('')
    expect(vim.state.mode).toBe('visual-line')
    vim.key('k')
    expect(vim.state.cursor.line).toBe(1)
    vim.key('Escape')
    expect(vim.selection()).toBeUndefined()
  })

  it('opens edit requests without changing the current cursor or visual selection', () => {
    const vim = new SourceVimController('first\nsecond\nlast')
    expect(vim.key('e')).toEqual({ handled: true, edit: true })
    expect(vim.state.cursor).toEqual({ line: 1, column: 0 })
    for (const linewise of [false, true]) {
      vim.select({ line: 3, column: 2 }, { line: 2, column: 1 }, linewise)
      const selected = vim.selection()
      const state = vim.state
      expect(vim.key('e')).toEqual({ handled: true, edit: true })
      expect(vim.selection()).toEqual(selected)
      expect(vim.state).toEqual(state)
    }
  })

  it('keeps word-end motions and character prefixes when e is part of a command', () => {
    const vim = new SourceVimController('one two three')
    expect(keys(vim, ['1', 'e']).cursor).toEqual({ line: 1, column: 2 })
    vim.key('0')
    expect(keys(vim, ['2', 'e']).cursor).toEqual({ line: 1, column: 6 })
    expect(keys(vim, ['g', 'e']).cursor).toEqual({ line: 1, column: 2 })
    vim.key('0')
    expect(keys(vim, ['y', 'e']).yank).toBe('one')
    expect(keys(vim, ['f', 'e']).cursor).toEqual({ line: 1, column: 2 })
    expect(vim.key('Ctrl+e').edit).toBeUndefined()
  })

  it('moves and yanks complete Unicode code points while keeping UTF-16 cursor offsets', () => {
    const vim = new SourceVimController('a😀b😀')
    vim.key('l')
    expect(vim.state.cursor.column).toBe(1)
    expect(keys(vim, ['v', 'y']).yank).toBe('😀')
    vim.key('l')
    expect(vim.state.cursor.column).toBe(3)
    vim.key('h')
    expect(vim.state.cursor.column).toBe(1)
    expect(keys(vim, ['y', 'l']).yank).toBe('😀')
    vim.setCursor({ line: 1, column: 2 })
    expect(vim.state.cursor.column).toBe(1)
    vim.key('$')
    expect(vim.state.cursor.column).toBe(4)
    expect(keys(vim, ['v', 'y']).yank).toBe('😀')
    vim.key('0')
    expect(keys(vim, ['y', 'f', '😀']).yank).toBe('a😀')
    keys(vim, ['0', 't', '😀', ';'])
    expect(vim.state.cursor.column).toBe(3)
  })

  it('applies counts to line scrolling and bounds the pending display', () => {
    const vim = new SourceVimController('one two')
    expect(keys(vim, ['3', 'Ctrl+e'])).toMatchObject({ scroll: 'line-down', scrollLines: 3 })
    for (let index = 0; index < 100; index += 1) vim.key('9')
    expect(vim.state.pending.length).toBeLessThanOrEqual(24)
    vim.key('Escape')
    expect(vim.state.pending).toBe('')
  })

  it('keeps the cursor in the scrolled viewport without changing a visual anchor', () => {
    const vim = new SourceVimController(Array.from({ length: 20 }, (_, index) => `line ${index}`).join('\n'))
    vim.select({ line: 3, column: 2 }, { line: 3, column: 2 }, false)
    vim.key('2')
    expect(vim.key('Ctrl+e', { firstVisibleLine: 3, lastVisibleLine: 7 })).toMatchObject({
      scroll: 'line-down', scrollLines: 2, cursor: { line: 5, column: 2 },
    })
    expect(vim.state.anchor).toEqual({ line: 3, column: 2 })
    expect(vim.state.mode).toBe('visual')
    vim.key('j')
    expect(vim.key('Ctrl+e', { firstVisibleLine: 5, lastVisibleLine: 9 })).toEqual({
      handled: true, scroll: 'line-down', scrollLines: 1,
    })
    expect(vim.state.cursor.line).toBe(6)
    vim.key('5')
    expect(vim.key('Ctrl+y', { firstVisibleLine: 6, lastVisibleLine: 10 })).toMatchObject({
      scroll: 'line-up', scrollLines: 5, cursor: { line: 5, column: 2 },
    })
    expect(vim.state.anchor).toEqual({ line: 3, column: 2 })
    expect(vim.key('Ctrl+y', { firstVisibleLine: 1, lastVisibleLine: 5 }).scrollLines).toBe(0)
    vim.setCursor({ line: 20, column: 0 })
    vim.key('9')
    expect(vim.key('Ctrl+e', { firstVisibleLine: 16, lastVisibleLine: 20 }).scrollLines).toBe(0)
    expect(vim.state.cursor.line).toBe(20)
  })

  it('resets incomplete or invalid sequences and bounds large counts', () => {
    const vim = new SourceVimController('one two\nthree')
    keys(vim, ['2', 'y', 'Escape'])
    expect(vim.state.pending).toBe('')
    keys(vim, ['g', 'q', 'j'])
    expect(vim.state.cursor.line).toBe(2)
    expect(keys(vim, ['y', 'q']).handled).toBe(true)
    expect(vim.state.pending).toBe('')
    keys(vim, ['9', '9', '9', '9', '9', '9', '9', 'w'])
    expect(vim.state.cursor).toEqual({ line: 2, column: 4 })
    expect(vim.key('Meta+k')).toEqual({ handled: false })
    vim.reset('')
    expect(keys(vim, ['v', 'y']).yank).toBe('')
  })
})
